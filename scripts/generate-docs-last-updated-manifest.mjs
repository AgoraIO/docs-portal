import { execFile } from 'node:child_process';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { promisify } from 'node:util';

const execFileAsync = promisify(execFile);
const GIT_LOG_DATE_MARKER = '@@';
const GIT_METADATA_ROOTS = ['content/docs', 'content/openapi'];
const OUTPUT_PATH = path.join(
  process.cwd(),
  'src/generated/docs-last-updated-manifest.ts',
);

async function main() {
  const manifest = await loadGitLastUpdatedIndex();

  if (
    (await pathExists(OUTPUT_PATH)) &&
    (!manifest || manifest.size === 0 || (await isGitHistoryIncomplete()))
  ) {
    console.warn(
      `[docs-last-updated] git history is unavailable or incomplete; keeping existing ${path.relative(process.cwd(), OUTPUT_PATH)}`,
    );
    return;
  }

  if (!manifest) {
    throw new Error(
      'Unable to generate docs last-updated manifest from Git history',
    );
  }

  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, renderManifest(manifest), 'utf8');

  console.log(
    `[docs-last-updated] generated ${manifest.size} entries at ${path.relative(process.cwd(), OUTPUT_PATH)}`,
  );
}

async function loadGitLastUpdatedIndex() {
  try {
    const { stdout } = await execFileAsync(
      'git',
      [
        'log',
        `--format=${GIT_LOG_DATE_MARKER}%cI`,
        '--name-only',
        '--',
        ...GIT_METADATA_ROOTS,
      ],
      {
        cwd: process.cwd(),
        encoding: 'utf8',
        maxBuffer: 64 * 1024 * 1024,
      },
    );

    return parseGitLastUpdatedIndex(stdout);
  } catch (error) {
    console.warn('[docs-last-updated] failed to read Git history', error);
    return null;
  }
}

async function isGitHistoryIncomplete() {
  try {
    const { stdout } = await execFileAsync(
      'git',
      ['rev-parse', '--is-shallow-repository'],
      {
        cwd: process.cwd(),
        encoding: 'utf8',
      },
    );

    return stdout.trim() === 'true';
  } catch {
    return true;
  }
}

async function pathExists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

function parseGitLastUpdatedIndex(stdout) {
  const index = new Map();
  let currentIso;

  for (const rawLine of stdout.split(/\r?\n/)) {
    const line = rawLine.trim();

    if (!line) {
      continue;
    }

    if (line.startsWith(GIT_LOG_DATE_MARKER)) {
      currentIso = line.slice(GIT_LOG_DATE_MARKER.length).trim();
      continue;
    }

    if (currentIso && !index.has(line)) {
      index.set(line, currentIso);
    }
  }

  return new Map(
    [...index.entries()].sort(([left], [right]) => left.localeCompare(right)),
  );
}

function renderManifest(manifest) {
  const entries = [...manifest.entries()]
    .map(([metadataPath, iso]) => renderManifestEntry(metadataPath, iso))
    .join('\n');

  return `// Generated by scripts/generate-docs-last-updated-manifest.mjs. Do not edit manually.\nexport const DOCS_LAST_UPDATED_BY_PATH: Record<string, string> = {\n${entries}\n};\n`;
}

function renderManifestEntry(metadataPath, iso) {
  const key = quoteString(metadataPath);
  const value = quoteString(new Date(iso).toISOString());
  const inlineEntry = `  ${key}: ${value},`;

  if (inlineEntry.length <= 80) {
    return inlineEntry;
  }

  return `  ${key}:\n    ${value},`;
}

function quoteString(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
