function collectOperations(document) {
  const operations = [];

  for (const [operationPath, pathItem] of Object.entries(document.paths ?? {})) {
    for (const [method, operation] of Object.entries(pathItem ?? {})) {
      if (!isHttpMethod(method) || !isRecord(operation) || typeof operation.operationId !== 'string') {
        continue;
      }

      operations.push({
        description:
          typeof operation.description === 'string' ? operation.description : undefined,
        method: method.toUpperCase(),
        operationId: operation.operationId,
        parameters: normalizeParameters(operation.parameters),
        path: operationPath,
        requestBody: normalizeRequestBody(operation.requestBody),
        responses: normalizeResponses(operation.responses),
        security: operation.security,
        servers: normalizeServers(
          operation.servers ?? pathItem?.servers ?? document.servers ?? [],
        ),
        summary: typeof operation.summary === 'string' ? operation.summary : undefined,
      });
    }
  }

  return operations.sort((left, right) =>
    left.operationId.localeCompare(right.operationId),
  );
}

function collectDocumentPayload(document) {
  const baseDocument = {
    ...(typeof document.openapi === 'string'
      ? { openapi: document.openapi }
      : {}),
    ...(isRecord(document.info) ? { info: document.info } : {}),
    ...(Array.isArray(document.servers) ? { servers: document.servers } : {}),
  };
  const operations = {};

  for (const [operationPath, pathItem] of Object.entries(document.paths ?? {})) {
    if (!isRecord(pathItem)) {
      continue;
    }

    for (const [method, operation] of Object.entries(pathItem)) {
      if (!isHttpMethod(method) || !isRecord(operation) || typeof operation.operationId !== 'string') {
        continue;
      }

      operations[operation.operationId] = {
        method,
        operation,
        path: operationPath,
      };
    }
  }

  return {
    base: baseDocument,
    operations,
  };
}

function collectOperationMethods(document) {
  const methods = {};

  for (const pathItem of Object.values(document.paths ?? {})) {
    if (!isRecord(pathItem)) {
      continue;
    }

    for (const [method, operation] of Object.entries(pathItem)) {
      if (
        !isHttpMethod(method) ||
        !isRecord(operation) ||
        typeof operation.operationId !== 'string'
      ) {
        continue;
      }

      methods[operation.operationId] = method.toUpperCase();
    }
  }

  return Object.fromEntries(
    Object.entries(methods).sort(([left], [right]) => left.localeCompare(right)),
  );
}

function collectRoutePayload(document, lane, locale) {
  const operationsById = new Map();

  for (const [operationPath, pathItem] of Object.entries(document.paths ?? {})) {
    if (!isRecord(pathItem)) {
      continue;
    }

    for (const [method, operation] of Object.entries(pathItem)) {
      if (!isHttpMethod(method) || !isRecord(operation) || typeof operation.operationId !== 'string') {
        continue;
      }

      operationsById.set(operation.operationId, {
        deprecated: operation.deprecated === true,
        description:
          typeof operation.description === 'string' ? operation.description : undefined,
        method,
        path: operationPath,
      });
    }
  }

  return Object.fromEntries(
    Object.entries(lane.operations)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([operationId, operationMeta]) => {
        const resolved = operationsById.get(operationId);

        if (!resolved) {
          throw new Error(
            `Missing operation "${operationId}" for lane "${lane.id}" locale "${locale}"`,
          );
        }

        return [
          operationId,
          {
            ...(resolved.deprecated ? { deprecated: true } : {}),
            ...(resolved.description
              ? { description: resolved.description }
              : {}),
            method: resolved.method,
            path: resolved.path,
            routeLeaf: operationMeta.routeLeaf,
            title: operationMeta.title[locale],
          },
        ];
      }),
  );
}

function normalizeParameters(value) {
  if (!Array.isArray(value)) {
    return [];
  }

  return value.flatMap((parameter) => {
    if (!isRecord(parameter)) {
      return [];
    }

    if (
      typeof parameter.name !== 'string' ||
      !['cookie', 'header', 'path', 'query'].includes(parameter.in)
    ) {
      return [];
    }

    return [
      {
        description:
          typeof parameter.description === 'string'
            ? parameter.description
            : undefined,
        example: parameter.example,
        examples: normalizeExamples(parameter.examples),
        in: parameter.in,
        name: parameter.name,
        required: parameter.required === true,
        schema: parameter.schema,
      },
    ];
  });
}

function normalizeRequestBody(value) {
  if (!isRecord(value) || !isRecord(value.content)) {
    return undefined;
  }

  const content = normalizeContent(value.content);

  return {
    content,
    contentTypes: Object.keys(content),
    description: typeof value.description === 'string' ? value.description : undefined,
    required: value.required === true,
  };
}

function normalizeResponses(value) {
  if (!isRecord(value)) {
    return {};
  }

  return Object.fromEntries(
    Object.entries(value).map(([status, response]) => [
      status,
      normalizeResponse(response),
    ]),
  );
}

function normalizeResponse(value) {
  if (!isRecord(value)) {
    return {};
  }

  return {
    content: isRecord(value.content) ? normalizeContent(value.content) : undefined,
    description: typeof value.description === 'string' ? value.description : undefined,
  };
}

function normalizeContent(value) {
  return Object.fromEntries(
    Object.entries(value).map(([contentType, media]) => [
      contentType,
      isRecord(media)
        ? {
            example: media.example,
            examples: normalizeExamples(media.examples),
            schema: media.schema,
          }
        : {},
    ]),
  );
}

function normalizeExamples(value) {
  if (!isRecord(value)) {
    return undefined;
  }

  return Object.fromEntries(
    Object.entries(value).map(([name, example]) => [
      name,
      isRecord(example) && 'value' in example ? { value: example.value } : {},
    ]),
  );
}

function normalizeServers(value) {
  if (!Array.isArray(value)) {
    return [];
  }

  return value.flatMap((server) => {
    if (!isRecord(server) || typeof server.url !== 'string') {
      return [];
    }

    return [
      {
        description:
          typeof server.description === 'string' ? server.description : undefined,
        url: server.url,
      },
    ];
  });
}

function isHttpMethod(value) {
  return ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'].includes(
    value,
  );
}

function isRecord(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}
