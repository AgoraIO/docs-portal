export const EXISTING_LINK_REPORT_JSON_PATH =
  'docs/migration/api-center-existing-link-normalization.json';
export const EXISTING_LINK_REPORT_MD_PATH =
  'docs/migration/api-center-existing-link-normalization.md';

function stableObject(value) {
  if (Array.isArray(value)) return value.map(stableObject);
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(
    Object.keys(value)
      .sort()
      .map((key) => [key, stableObject(value[key])]),
  );
}

async function readJsonIfPresent(filePath, fallback) {
  try {
    return JSON.parse(await fs.readFile(filePath, 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') return fallback;
    throw error;
  }
}

async function readOwnershipTargets(repoRoot, ownershipPaths) {
  const targets = new Set();
  for (const ownershipPath of ownershipPaths) {
    const ownership = await readJsonIfPresent(
      path.resolve(repoRoot, ownershipPath),
      { files: [] },
    );
    for (const record of ownership.files ?? []) targets.add(record.targetPath);
  }
  return targets;
}

function visibleMdxTargets(manifest) {
  const grouped = new Map();
  for (const page of manifest.pageEvidence ?? []) {
    const targetPath = page.sourceResolution?.targetPath;
    if (
      page.aliasOf ||
      !page.sourceResolution?.targetExists ||
      !targetPath?.startsWith('content/docs/') ||
      !/\.mdx?$/i.test(targetPath)
    ) {
      continue;
    }
    const current = grouped.get(targetPath) ?? [];
    current.push(page.requestedUrl);
    grouped.set(targetPath, current);
  }
  return grouped;
}

function mappingKey(change) {
  return [
    change.action,
    change.href,
    change.targetHref ?? '',
    change.source,
  ].join('\u0000');
}

function mergeMappings(previous, changes, visibleTargets) {
  const mappings = new Map();
  for (const mapping of previous.mappings ?? []) {
    const occurrences = (mapping.occurrences ?? []).filter((occurrence) =>
      visibleTargets.has(occurrence.targetPath),
    );
    if (occurrences.length > 0) {
      mappings.set(mappingKey(mapping), { ...mapping, occurrences });
    }
  }
  for (const change of changes) {
    const key = mappingKey(change);
    for (const [existingKey, existing] of mappings) {
      if (
        existingKey === key ||
        existing.href !== change.href ||
        existing.source !== change.source
      ) {
        continue;
      }
      existing.occurrences = existing.occurrences.filter(
        (item) => item.targetPath !== change.sourcePath,
      );
      if (existing.occurrences.length === 0) mappings.delete(existingKey);
    }
    const mapping = mappings.get(key) ?? {
      action: change.action,
      href: change.href,
      source: change.source,
      targetHref: change.targetHref,
      occurrences: [],
    };
    const occurrence = mapping.occurrences.find(
      (item) => item.targetPath === change.sourcePath,
    );
    if (occurrence) occurrence.count += 1;
    else mapping.occurrences.push({ count: 1, targetPath: change.sourcePath });
    mappings.set(key, mapping);
  }
  return [...mappings.values()]
    .map((mapping) => ({
      ...mapping,
      occurrences: mapping.occurrences.sort((left, right) =>
        left.targetPath.localeCompare(right.targetPath),
      ),
    }))
    .sort((left, right) => mappingKey(left).localeCompare(mappingKey(right)));
}

function countOccurrences(mappings, action) {
  return mappings
    .filter((mapping) => !action || mapping.action === action)
    .flatMap((mapping) => mapping.occurrences)
    .reduce((sum, occurrence) => sum + occurrence.count, 0);
}

function sourceContainsMappedHref(source, href) {
  return (
    source.includes(`](${href})`) ||
    source.includes(`](${href} `) ||
    source.includes(`href="${href}"`) ||
    source.includes(`href='${href}'`)
  );
}

function reportMarkdown(report) {
  const lines = [
    '# API Center Existing-target Link Normalization',
    '',
    '> Generated by `scripts/normalize-api-center-existing-links.mjs`. Do not edit by hand.',
    '',
    `- Visible existing MDX targets: ${report.counts.visibleExistingMdxTargets}`,
    `- Preserved MDX targets normalized by this script: ${report.counts.preservedMdxTargets}`,
    `- Generator-owned targets skipped: ${report.counts.ownedMdxTargets}`,
    `- Local link rewrites: ${report.counts.rewrittenLocal}`,
    `- External canonical rewrites: ${report.counts.rewrittenExternal}`,
    `- Source-only links rendered as text: ${report.counts.renderedAsText}`,
    `- Fragments normalized: ${report.counts.fragmentsNormalized}`,
    `- Unresolved fragments removed: ${report.counts.fragmentsRemoved}`,
    `- Remaining old-site body links: ${report.counts.remainingLegacyBodyLinks}`,
    `- Invalid normalized local links: ${report.counts.invalidNormalizedLinks}`,
    `- Errors: ${report.counts.errors}`,
    '',
    '## Normalization types',
    '',
    `- \`rewritten-local\`: ${report.counts.rewrittenLocal}`,
    `- \`rewritten-external\`: ${report.counts.rewrittenExternal}`,
    `- \`rendered-as-text\`: ${report.counts.renderedAsText}`,
    `- \`fragment-normalized\`: ${report.counts.fragmentsNormalized}`,
    `- \`fragment-removed\`: ${report.counts.fragmentsRemoved}`,
    '',
    '## Remaining old-site body links',
    '',
  ];
  if (report.remaining.length === 0) {
    lines.push('- None.', '');
  } else {
    lines.push('| Source | Link kind | Href |', '| --- | --- | --- |');
    for (const item of report.remaining) {
      lines.push(
        `| \`${item.sourcePath}\` | ${item.source} | \`${item.href}\` |`,
      );
    }
    lines.push('');
  }
  lines.push('## Invalid normalized local links', '');
  if (report.invalidNormalizedLinks.length === 0) {
    lines.push('- None.', '');
  } else {
    lines.push('| Source | Href | Reason |', '| --- | --- | --- |');
    for (const item of report.invalidNormalizedLinks) {
      lines.push(
        `| \`${item.sourcePath}\` | \`${item.href}\` | ${item.reason} |`,
      );
    }
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}

export async function normalizeExistingApiCenterLinks({
  repoRoot = process.cwd(),
  manifestPath = 'docs/migration/api-center-html-manifest.json',
  pathMapPath = 'docs/migration/path-map.csv',
  ownershipPaths = API_CENTER_OWNERSHIP_LEDGERS,
  reportJsonPath = EXISTING_LINK_REPORT_JSON_PATH,
  reportMarkdownPath = EXISTING_LINK_REPORT_MD_PATH,
  mode = 'write',
} = {}) {
  const root = path.resolve(repoRoot);
  const manifest = JSON.parse(
    await fs.readFile(path.resolve(root, manifestPath), 'utf8'),
  );
  const pathMapRows = parseCsv(
    await fs.readFile(path.resolve(root, pathMapPath), 'utf8'),
  );
  const routeMap = buildLegacyRouteMap(
    manifest,
    pathMapRows,
    await loadFaqMappingRows(root),
  );
  const groupedTargets = visibleMdxTargets(manifest);
  const ownedTargets = await readOwnershipTargets(root, ownershipPaths);
  const selected = [...groupedTargets.entries()].filter(
    ([targetPath]) => !ownedTargets.has(targetPath),
  );
  const changes = [];
  const unresolved = [];
  const changedFiles = [];
  const previous = await readJsonIfPresent(path.resolve(root, reportJsonPath), {
    mappings: [],
  });
  const previousByTarget = new Map();
  for (const mapping of previous.mappings ?? []) {
    if (!['rewritten-external', 'rewritten-local'].includes(mapping.action)) {
      continue;
    }
    for (const occurrence of mapping.occurrences ?? []) {
      const current = previousByTarget.get(occurrence.targetPath) ?? [];
      current.push(mapping);
      previousByTarget.set(occurrence.targetPath, current);
    }
  }
  const fragmentIndex = await buildLocalFragmentIndex({ repoRoot: root });
  for (const [targetPath, sourceUrls] of selected) {
    const absolute = path.resolve(root, targetPath);
    const current = await fs.readFile(absolute, 'utf8');
    const sourceUrl = sourceUrls[0] ?? 'https://doc.shengwang.cn/api-center';
    let pending = current;
    for (const mapping of previousByTarget.get(targetPath) ?? []) {
      if (!mapping.targetHref) continue;
      const resolved = rewriteLegacyHref(mapping.href, { routeMap, sourceUrl });
      const reconciled = reconcileMappedBodyLink(pending, {
        fromHref: mapping.targetHref,
        sourcePath: targetPath,
        toHref: resolved.href,
      });
      pending = reconciled.source;
      changes.push(
        ...reconciled.changes.map((change) => ({
          ...change,
          href: mapping.href,
        })),
      );
      unresolved.push(...reconciled.unresolved);
    }
    const normalized = rewriteLegacyBodyLinks(pending, {
      routeMap,
      sourcePath: targetPath,
      sourceUrl,
    });
    changes.push(...normalized.changes);
    unresolved.push(...normalized.unresolved);
    const fragments =
      normalized.changes.length > 0 || previousByTarget.has(targetPath)
        ? await rewriteLocalFragmentLinks(normalized.source, {
            fragmentIndex,
            sourceRoute: targetPathToRoute(targetPath),
          })
        : { body: normalized.source, warnings: [] };
    for (const warning of fragments.warnings) {
      changes.push({
        action: warning.unresolved ? 'fragment-removed' : 'fragment-normalized',
        href: warning.from,
        source: 'markdown',
        sourcePath: targetPath,
        targetHref: warning.to,
      });
    }
    if (fragments.body !== current) {
      changedFiles.push(targetPath);
      if (mode === 'write') await fs.writeFile(absolute, fragments.body);
    }
  }
  if (mode === 'check' && changedFiles.length > 0) {
    throw new Error(
      `${changedFiles.length} preserved API Center MDX targets still need old-site link normalization.`,
    );
  }

  const visibleTargetSet = new Set(groupedTargets.keys());
  const mappings = mergeMappings(previous, changes, visibleTargetSet);
  const activeMappingKeys = new Set();
  const activeSourcePaths = new Set();
  const sourceCache = new Map();
  for (const mapping of mappings) {
    if (mapping.action !== 'rewritten-local' || !mapping.targetHref) continue;
    for (const occurrence of mapping.occurrences ?? []) {
      let source = sourceCache.get(occurrence.targetPath);
      if (source === undefined) {
        source = await fs.readFile(
          path.resolve(root, occurrence.targetPath),
          'utf8',
        );
        sourceCache.set(occurrence.targetPath, source);
      }
      if (!sourceContainsMappedHref(source, mapping.targetHref)) continue;
      const sourcePath = occurrence.targetPath.replace(/^content\/docs\//, '');
      activeSourcePaths.add(sourcePath);
      activeMappingKeys.add(`${sourcePath}\u0000${mapping.targetHref}`);
    }
  }
  const normalizedLinkStats = auditDocsLinks({
    docsRoot: path.resolve(root, 'content/docs'),
    sourcePaths: [...activeSourcePaths],
  });
  const invalidNormalizedLinks = normalizedLinkStats.invalidLinks
    .filter((issue) =>
      activeMappingKeys.has(`${issue.sourcePath}\u0000${issue.href}`),
    )
    .sort((left, right) =>
      `${left.sourcePath}\u0000${left.href}`.localeCompare(
        `${right.sourcePath}\u0000${right.href}`,
      ),
    );
  const remaining = [];
  for (const [targetPath] of groupedTargets) {
    const source = await fs.readFile(path.resolve(root, targetPath), 'utf8');
    remaining.push(...findLegacyBodyLinks(source, { sourcePath: targetPath }));
  }
  remaining.push(...unresolved);
  const uniqueRemaining = [
    ...new Map(
      remaining.map((item) => [
        `${item.sourcePath}\u0000${item.source}\u0000${item.href}`,
        item,
      ]),
    ).values(),
  ].sort((left, right) =>
    `${left.sourcePath}\u0000${left.href}`.localeCompare(
      `${right.sourcePath}\u0000${right.href}`,
    ),
  );
  const report = stableObject({
    schemaVersion: 1,
    counts: {
      errors: uniqueRemaining.length + invalidNormalizedLinks.length,
      fragmentsNormalized: countOccurrences(mappings, 'fragment-normalized'),
      fragmentsRemoved: countOccurrences(mappings, 'fragment-removed'),
      invalidNormalizedLinks: invalidNormalizedLinks.length,
      ownedMdxTargets: [...groupedTargets.keys()].filter((targetPath) =>
        ownedTargets.has(targetPath),
      ).length,
      preservedMdxTargets: selected.length,
      remainingLegacyBodyLinks: uniqueRemaining.length,
      renderedAsText: countOccurrences(mappings, 'rendered-as-text'),
      rewrittenExternal: countOccurrences(mappings, 'rewritten-external'),
      rewrittenLocal: countOccurrences(mappings, 'rewritten-local'),
      visibleExistingMdxTargets: groupedTargets.size,
    },
    mappings,
    invalidNormalizedLinks,
    remaining: uniqueRemaining,
  });
  const files = [
    [reportJsonPath, `${JSON.stringify(report, null, 2)}\n`],
    [reportMarkdownPath, reportMarkdown(report)],
  ];
  for (const [targetPath, contents] of files) {
    const absolute = path.resolve(root, targetPath);
    if (mode === 'check') {
      const current = await fs.readFile(absolute, 'utf8');
      if (current !== contents) {
        throw new Error(
          `Generated normalization report is stale: ${targetPath}`,
        );
      }
    } else {
      await fs.mkdir(path.dirname(absolute), { recursive: true });
      await fs.writeFile(absolute, contents);
    }
  }
  if (report.counts.errors > 0) {
    throw new Error(
      `Existing-target normalization left ${report.counts.errors} old-site body links.`,
    );
  }
  return { changedFiles, report };
}
