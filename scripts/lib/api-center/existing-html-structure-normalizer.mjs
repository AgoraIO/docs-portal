import fs from 'node:fs/promises';
import path from 'node:path';
import * as cheerio from 'cheerio';
import { detailedDescriptionTitleMode } from './html-to-mdx.mjs';
import { renderStableAnchor } from './migration-framework.mjs';

export const EXISTING_HTML_STRUCTURE_REPORT_JSON_PATH =
  'docs/migration/api-center-existing-html-structure.json';
export const EXISTING_HTML_STRUCTURE_REPORT_MD_PATH =
  'docs/migration/api-center-existing-html-structure.md';

export const API_CENTER_EXISTING_HTML_SOURCE_TARGET_ROOTS = Object.freeze([
  {
    sourceDir: 'html-docs/flexible-classroom/Android/API',
    targetDir:
      'content/docs/zh-CN/api-reference/flexible-classroom/android/api-reference/edu-context',
  },
  {
    sourceDir: 'html-docs/flexible-classroom/iOS/API',
    targetDir:
      'content/docs/zh-CN/api-reference/flexible-classroom/ios/api-reference/edu-context',
  },
]);

function stableObject(value) {
  if (Array.isArray(value)) return value.map(stableObject);
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(
    Object.keys(value)
      .sort()
      .map((key) => [key, stableObject(value[key])]),
  );
}

async function exists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

function targetNameForSource(sourceName) {
  return sourceName.replace(/_/g, '-').replace(/\.html$/i, '.mdx');
}

function insertImplicitDetailHeading(source, id) {
  const anchor = renderStableAnchor(id);
  const anchorIndex = source.indexOf(anchor);
  if (anchorIndex < 0) return { source, status: 'missing-anchor' };

  const afterAnchorIndex = anchorIndex + anchor.length;
  const afterAnchor = source.slice(afterAnchorIndex);
  const leadingWhitespace =
    afterAnchor.match(/^(?:[ \t]*\r?\n)+[ \t]*/)?.[0] ?? '';
  const nextContent = afterAnchor.slice(leadingWhitespace.length);
  if (/^#{1,6}[ \t]+详情(?:[ \t]*(?:\r?\n|$))/.test(nextContent)) {
    return { source, status: 'present' };
  }

  const newline = source.includes('\r\n') ? '\r\n' : '\n';
  return {
    source: `${source.slice(0, afterAnchorIndex)}${newline}${newline}### 详情${newline}${newline}${nextContent}`,
    status: 'inserted',
  };
}

function reportMarkdown(report) {
  const lines = [
    '# API Center Existing HTML Structure Normalization',
    '',
    '> Generated by `scripts/normalize-api-center-existing-html-structure.mjs`. Do not edit by hand.',
    '',
    `- HTML source files: ${report.counts.sourceFiles}`,
    `- Existing MDX target files: ${report.counts.targetFiles}`,
    `- Normalized detail headings: ${report.counts.normalizedDetailHeadings}`,
    `- Source sections suppressed by \`no-title\`: ${report.counts.sourceSectionsSuppressedByNoTitle}`,
    `- Source sections with explicit headings: ${report.counts.sourceSectionsWithExplicitHeadings}`,
    `- Errors: ${report.counts.errors}`,
    '',
    '## Normalization types',
    '',
    `- \`implicit-detail-heading\`: ${report.counts.sourceSectionsWithImplicitDetailTitles}`,
    '',
    '## Warning explanations',
    '',
    '- `missing-target`: An authoritative HTML source page has no mapped local MDX target.',
    '- `missing-detail-anchor`: A source detail section has no corresponding stable anchor in the local MDX target.',
    '',
    '## Errors',
    '',
  ];
  if (report.errors.length === 0) {
    lines.push('- None.', '');
  } else {
    lines.push(
      '| Code | Source | Target | Fragment |',
      '| --- | --- | --- | --- |',
    );
    for (const error of report.errors) {
      lines.push(
        `| \`${error.code}\` | \`${error.sourcePath}\` | \`${error.targetPath}\` | ${error.id ? `\`${error.id}\`` : '-'} |`,
      );
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

export async function normalizeExistingHtmlStructure({
  repoRoot = process.cwd(),
  oldRoot = process.env.API_CENTER_OLD_ROOT,
  sourceTargetRoots = API_CENTER_EXISTING_HTML_SOURCE_TARGET_ROOTS,
  reportJsonPath = EXISTING_HTML_STRUCTURE_REPORT_JSON_PATH,
  reportMarkdownPath = EXISTING_HTML_STRUCTURE_REPORT_MD_PATH,
  mode = 'write',
} = {}) {
  if (!oldRoot) {
    throw new Error(
      'Pass oldRoot or set API_CENTER_OLD_ROOT to the durable shengwang-doc-source checkout.',
    );
  }
  if (!['check', 'write'].includes(mode)) {
    throw new Error(`Unsupported normalization mode: ${mode}`);
  }

  const root = path.resolve(repoRoot);
  const sourceRoot = path.resolve(oldRoot);
  const changedFiles = [];
  const errors = [];
  const mappings = [];
  let sourceFiles = 0;
  let targetFiles = 0;
  let normalizedDetailHeadings = 0;
  let sourceSectionsSuppressedByNoTitle = 0;
  let sourceSectionsWithExplicitHeadings = 0;
  let sourceSectionsWithImplicitDetailTitles = 0;

  for (const mappingRoot of sourceTargetRoots) {
    const absoluteSourceDir = path.resolve(sourceRoot, mappingRoot.sourceDir);
    const sourceNames = (await fs.readdir(absoluteSourceDir))
      .filter((name) => name.endsWith('.html'))
      .sort();
    for (const sourceName of sourceNames) {
      sourceFiles += 1;
      const sourcePath = path.posix.join(mappingRoot.sourceDir, sourceName);
      const targetPath = path.posix.join(
        mappingRoot.targetDir,
        targetNameForSource(sourceName),
      );
      const absoluteTarget = path.resolve(root, targetPath);
      const html = await fs.readFile(
        path.resolve(sourceRoot, sourcePath),
        'utf8',
      );
      const $ = cheerio.load(html);
      const sections = $('section').toArray();
      const implicitIds = [];
      for (const section of sections) {
        const element = $(section);
        const titleMode = detailedDescriptionTitleMode(element);
        if (titleMode === 'suppressed') {
          sourceSectionsSuppressedByNoTitle += 1;
        } else if (titleMode === 'explicit') {
          sourceSectionsWithExplicitHeadings += 1;
        } else if (titleMode === 'implicit') {
          sourceSectionsWithImplicitDetailTitles += 1;
          implicitIds.push(element.attr('id') ?? element.attr('name'));
        }
      }

      if (!(await exists(absoluteTarget))) {
        errors.push({
          code: 'missing-target',
          sourcePath,
          targetPath,
        });
        continue;
      }
      targetFiles += 1;
      let pending = await fs.readFile(absoluteTarget, 'utf8');
      const current = pending;
      for (const id of implicitIds) {
        const normalized = insertImplicitDetailHeading(pending, id);
        pending = normalized.source;
        if (normalized.status === 'missing-anchor') {
          errors.push({
            code: 'missing-detail-anchor',
            id,
            sourcePath,
            targetPath,
          });
          continue;
        }
        normalizedDetailHeadings += 1;
        mappings.push({
          id,
          sourcePath,
          targetPath,
          type: 'implicit-detail-heading',
        });
      }
      if (pending !== current) {
        changedFiles.push(targetPath);
        if (mode === 'write') await fs.writeFile(absoluteTarget, pending);
      }
    }
  }

  changedFiles.sort();
  mappings.sort((left, right) =>
    `${left.targetPath}\u0000${left.id}`.localeCompare(
      `${right.targetPath}\u0000${right.id}`,
    ),
  );
  errors.sort((left, right) =>
    `${left.targetPath}\u0000${left.id ?? ''}`.localeCompare(
      `${right.targetPath}\u0000${right.id ?? ''}`,
    ),
  );
  const report = stableObject({
    schemaVersion: 1,
    counts: {
      errors: errors.length,
      normalizedDetailHeadings,
      sourceFiles,
      sourceSectionsSuppressedByNoTitle,
      sourceSectionsWithExplicitHeadings,
      sourceSectionsWithImplicitDetailTitles,
      targetFiles,
    },
    errors,
    mappings,
  });

  if (mode === 'check' && changedFiles.length > 0) {
    throw new Error(
      `${changedFiles.length} existing HTML-derived MDX target(s) still need structure normalization.`,
    );
  }
  if (errors.length > 0) {
    throw new Error(
      `Existing HTML structure normalization found ${errors.length} source/target error(s).`,
    );
  }

  const files = [
    [reportJsonPath, `${JSON.stringify(report, null, 2)}\n`],
    [reportMarkdownPath, reportMarkdown(report)],
  ];
  for (const [targetPath, contents] of files) {
    const absolute = path.resolve(root, targetPath);
    if (mode === 'check') {
      const current = await fs.readFile(absolute, 'utf8');
      if (current !== contents) {
        throw new Error(
          `Generated normalization report is stale: ${targetPath}`,
        );
      }
    } else {
      await fs.mkdir(path.dirname(absolute), { recursive: true });
      await fs.writeFile(absolute, contents);
    }
  }

  return { changedFiles, report };
}
